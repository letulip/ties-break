// ⚠⚠ IT IS A ONE-OFF AND NOT A BUILD STEP, which is the round's own ruling: «its output is committed
// as ordinary source – no build step, no codegen in the pipeline, boring TypeScript intact». Nothing
// in `npm run check`, `npm run build` or the dev server runs this file. What keeps the committed
// module honest is `tests/round44-corpus-roundtrip.test.ts`, which re-parses the document on every
// run and compares it to the committed catalogue STRING FOR STRING – so a hand-edit of the generated
// file goes red, and so does a document edit that was never re-emitted.
//
// ⚠ RE-RUNNING IT IS THE ONLY LEGITIMATE WAY TO CHANGE THE 43. If the owner edits a line in
