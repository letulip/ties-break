/** The keys no row of the grid reaches, each with its reason.
 *  · TWELVE ARE UNREACHABLE BY CONSTRUCTION, and the old code had the same twelve branches (`outcomeLine` spelt them through `descriptorOf`): the beat's HERO is the player who won the game or the set,
 *    so the deciding point is hers – her own last ball is an ace or a winner, never a miss («She loses the point with …», seven), and the other player's last ball is a miss or a double fault, never a
 *    winner or an ace («{0} wins the {1} with …», three; «{0} ends it with a winner {1}.» and «{0} shots, and {1} ends it {2}.», the two non-hero winner moulds of `mannerLine`). They are kept so a branch that
 *    cannot be reached today and can tomorrow does not fall back to English; they cost a translator twelve rows, and the editorial doc already spells the hero-loses family (RU-08 §16.3).
 *  · ONE IS REACHABLE AND SIMPLY RARE: an ace into the body at a deciding point (20% of serves go there, and an ace is the clause of a break, a hold or a set in about one beat in sixty) – §3's second test finds it. */
