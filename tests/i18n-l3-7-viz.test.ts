describe('§3 completeness – the keys the grid reaches', () => {
  it('every key of the three files is reached by the commentary grid, the preview grid or the lead table – bar the named few', () => {
    const reached = new Set<string>([...GRID_REACHED, ...PREVIEW_REACHED])
    const unreached = SCANNED.filter((k) => !reached.has(k))
    // the keys no seeded match, rung or packet of the grid can say – each with the reason it is still a key:
    //   the 21+ count forms and set ordinals beyond the fifth are digits, not keys; `and a place in the round of {0}` needs a round of 128 or 64 whose label a played match reaches (it is in the grid: opener rows of the big draws)
    expect(unreached, 'keys no row of the grid reached').toEqual(UNREACHED)
  })
})
/** The keys no row of the grid reaches, each with its reason.
 *  · TWELVE ARE UNREACHABLE BY CONSTRUCTION, and the old code had the same twelve branches (`outcomeLine` spelt them through `descriptorOf`): the beat's HERO is the player who won the game or the set,
 *    so the deciding point is hers – her own last ball is an ace or a winner, never a miss («She loses the point with …», seven), and the other player's last ball is a miss or a double fault, never a
 *    winner or an ace («{0} wins the {1} with …», three; «{0} ends it with a winner {1}.» and «{0} shots, and {1} ends it {2}.», the two non-hero winner moulds of `mannerLine`). They are kept so a branch that
 *    cannot be reached today and can tomorrow does not fall back to English; they cost a translator twelve rows, and the editorial doc already spells the hero-loses family (RU-08 §16.3).
 *  · ONE IS REACHABLE AND SIMPLY RARE: an ace into the body at a deciding point (20% of serves go there, and an ace is the clause of a break, a hold or a set in about one beat in sixty) – §3's second test finds it. */
const UNREACHED: string[] = [
  'She loses the point with a double fault.',
  'She loses the point with a long groundstroke.',
  'She loses the point with a long return.',
  'She loses the point with a netted groundstroke.',
  'She loses the point with a netted return.',
  'She loses the point with a wide groundstroke.',
  'She loses the point with a wide return.',
  '{0} ends it with a winner {1}.',
  '{0} shots, and {1} ends it {2}.',
  '{0} wins the {1} with a second-serve ace {2}.',
  '{0} wins the {1} with a winner {2}.',
  '{0} wins the {1} with an ace {2}.',
  'into the body',
].sort()

describe('§3b the rare one is sayable', () => {
  it('an ace into the body at a deciding point: seed l37-body-95 (found by a search of 800 grass matches; one build is the proof)', () => {
    const A: MatchPlayer = { id: 'kid', name: 'Bianca Tran', serve: 78, ret: 55, composure: 42, stamina: 61, groundstrokes: 56 }
    const B: MatchPlayer = { id: 'opp', name: 'Dana Delgado', serve: 60, ret: 57, composure: 55, stamina: 60, groundstrokes: 58 }
    const opts = { surface: 'grass' as const, tour: 'wta' as const, seed: 'l37-body-95' }
    const m = annotateMatch(simulateMatch(A, B, opts), A, B, opts)
    const beat = buildCommentary(m, A.name, B.name, null).find((b) => /ace into the body/.test(b.text))
    expect(beat?.text).toBe('Bianca serves out the first set. She wins the point with an ace into the body.')
    expect(beat?.textC && renderCopyRef(beat.textC, EN)).toBe(beat?.text)
    const keys = new Set<string>()
    keysOf(beat?.textC, keys)
    expect(keys.has('into the body')).toBe(true)
  })
})

