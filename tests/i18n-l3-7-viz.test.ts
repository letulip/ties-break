/** every `cp` template in a file, as the key `cp` makes of it */
function cpKeys(rel: string): string[] {
  const sf = ts.createSourceFile(rel, SRC(rel), ts.ScriptTarget.Latest, true)
  const out: string[] = []
  const go = (n: ts.Node): void => {
    if (ts.isTaggedTemplateExpression(n) && n.tag.getText() === 'cp') {
      const tpl = n.template
      if (ts.isNoSubstitutionTemplateLiteral(tpl)) out.push(tpl.text)
      else {
        let k = tpl.head.text
        tpl.templateSpans.forEach((s, i) => {
          k += `{${i}}${s.literal.text}`
        })
        out.push(k)
      }
    }
    ts.forEachChild(n, go)
  }
  go(sf)
  return out
}
const SCANNED = [...new Set(FILES.flatMap(cpKeys))].sort()

if (process.env.L37_WRITE_KEYS) {
  const body = SCANNED.map((k) => `  ${JSON.stringify(k)},`).join('\n')
  writeFileSync(
    resolve(ROOT, 'tests/helpers/l3-7-viz-keys.ts'),
    `// GENERATED by tests/i18n-l3-7-viz.test.ts (\`L37_WRITE_KEYS=1 npx vitest run --project unit tests/i18n-l3-7-viz.test.ts\`) and held to the scan by its §1 – the \`cp\` keys of src/viz/commentary.ts, preview.ts and lines.ts.\n// Class (b): assembled by the viewer's builders at render time, never stored, so the frozen v92 table (a table of STORED rows) has no entry for any of them.\nexport const VIZ_CLASS_B_KEYS: readonly string[] = [\n${body}\n]\n`,
  )
}

/** every key a ref names, nested ones included */
function keysOf(ref: CopyRef | undefined, into: Set<string>): void {
  if (!ref) return
  into.add(ref.k)
  for (const p of ref.p ?? []) if (typeof p === 'object' && p !== null) keysOf(p as CopyRef, into)
}

describe('§1 the key law – the viz files\' cp keys are the listed ones, wired, and plain', () => {
  it('the scan equals the list (a new sentence, or a reworded one, is a decision)', () => {
    expect([...VIZ_CLASS_B_KEYS].sort()).toEqual(SCANNED)
  })

  it('every key is a key of the English catalog (the extractor reads them)', () => {
    const catalog = JSON.parse(SRC('src/i18n/catalog.en.json')) as { keys: Record<string, unknown> }
    const missing = SCANNED.filter((k) => !(k in catalog.keys))
    expect(missing).toEqual([])
  })

  it('no key carries a context tag, a brace the formatter would eat, or an edge space (the English renders as written)', () => {
    for (const k of SCANNED) {
      expect(splitContext(k).ctx, k).toBeNull()
      expect(k.includes('\\'), `a backslash in ${k} – the formatter would read it as an escape`).toBe(false)
      expect(k, `edge space in «${k}»`).toBe(k.trim())
      const holes = [...k.matchAll(/\{(\d+)\}/g)].map((m) => Number(m[1]))
      expect(holes, k).toEqual(holes.map((_, i) => i))
    }
  })

  it('the joins are the two generic keys (`{0} {1}` and `{0} {1} {2}`) – a clause chain is never a flattened key', () => {
    expect(SCANNED.filter((k) => /^\{\d+\}( \{\d+\})+$/.test(k))).toEqual(['{0} {1}', '{0} {1} {2}'])
  })
})

describe('§2 refs render === strings – the grid, the preview and the booth pools', () => {
  it('every beat of every build: the lead and the text render to the English the beat carries; the refs are JSON-safe', () => {
    let beats = 0
    const reached = new Set<string>()
    const bad: string[] = []
    eachCommentary((label, list) => {
      for (const b of list) {
        beats++
        if (b.lead === null) {
          if (b.leadC !== undefined) bad.push(`${label} lead is null but leadC is set`)
        } else {
          if (!b.leadC) bad.push(`${label} ${b.kind}: lead without a ref`)
          else if (renderCopyRef(b.leadC, EN) !== b.lead) bad.push(`${label} ${b.kind}: lead «${b.lead}» renders «${renderCopyRef(b.leadC, EN)}»`)
        }
        if (!b.textC) bad.push(`${label} ${b.kind}: text without a ref`)
        else {
          if (renderCopyRef(b.textC, EN) !== b.text) bad.push(`${label} ${b.kind}: «${b.text}» renders «${renderCopyRef(b.textC, EN)}»`)
          if (JSON.stringify(JSON.parse(JSON.stringify(b.textC))) !== JSON.stringify(b.textC)) bad.push(`${label}: ref is not JSON-safe`)
        }
        keysOf(b.leadC, reached)
        keysOf(b.textC, reached)
      }
    })
    expect(beats, 'a non-empty denominator').toBeGreaterThan(50_000)
    expect(bad.slice(0, 8)).toEqual([])
    GRID_REACHED = reached
  })

  it('every preview line of every build: `c` renders to the text', () => {
    let lines = 0
    const bad: string[] = []
    const reached = new Set<string>()
    for (const { label, input } of previewInputs()) {
      for (const l of buildPreview(input)) {
        lines++
        if (!l.c) bad.push(`${label} ${l.key}: no ref`)
        else if (renderCopyRef(l.c, EN) !== l.text) bad.push(`${label} ${l.key}: «${l.text}» renders «${renderCopyRef(l.c, EN)}»`)
        keysOf(l.c, reached)
      }
    }
    expect(lines, 'a non-empty denominator').toBeGreaterThan(40_000)
    expect(bad.slice(0, 8)).toEqual([])
    PREVIEW_REACHED = reached
  })

  it('the booth pools: every cell of the three lineage pools returns a Line whose ref renders to its text, for names with awkward characters too', () => {
    for (const ctx of [{ proTitles: 6, collegeTitles: 0, slams: 1 }, { proTitles: 0, collegeTitles: 1, slams: 0 }, { proTitles: 0, collegeTitles: 0, slams: 0 }]) {
      const pool = boothLineageLines({ side: 0, ...ctx })
      expect(pool.length).toBe(2)
      for (const cell of pool) {
        for (const who of ['Nadia', "O'Brien-Smith", 'Top seed', '{0}', 'Ines {1} Duval']) {
          const l = cell(who)
          expect(renderCopyRef(l.c, EN), who).toBe(l.text)
          expect(l.text, 'the name is a param, byte for byte').toContain(who)
        }
      }
    }
  })
})

let GRID_REACHED = new Set<string>()
